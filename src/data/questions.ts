/** 사용자가 직접 입력한 문장에서 키워드를 뽑아낸다 (조사 제거 후 2글자 이상 명사 후보) */
const PARTICLES = /(을|를|이|가|은|는|에|에서|으로|로|와|과|의|도|만|께서|부터|까지|처럼|보다)$/;
const STOP = new Set([
  '무엇', '어떻게', '어떤', '왜', '누가', '언제', '어디', '그리고', '하지만', '그런', '이런',
  '본인', '자신', '말씀', '설명', '이야기', '생각', '대해', '대한', '있는', '있나요', '인가요',
  '주세요', '해주세요', '부탁드립니다', '있습니까', '합니까', '하시나요', '하나요', '같이', '한번',
]);

export function extractKeywords(text: string): string[] {
  const out: string[] = [];
  for (const raw of text.split(/[\s,./?!"'`()[\]{}<>~·:;]+/)) {
    const w = raw.replace(/[^가-힣a-zA-Z0-9]/g, '');
    if (w.length < 2) continue;
    const base = w.replace(PARTICLES, '');
    const word = base.length >= 2 ? base : w;
    if (STOP.has(word) || STOP.has(w)) continue;
    if (/^(하|되|같|보|주)/.test(word) && word.length <= 2) continue;
    if (!out.includes(word)) out.push(word);
  }
  return out.slice(0, 8);
}

export function makeQuestion(text: string): Question {
  return { id: `u${++seq}`, text: text.trim(), category: '직접 입력', keywords: extractKeywords(text) };
}
